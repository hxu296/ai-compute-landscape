#!/usr/bin/env python3
"""Generate browser data from the independent review snapshots; never rewrite nc.js."""
import argparse
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
# The full source keeps the site under neocloud/site; the public checkout is the site itself.
if (ROOT/'site'/'research').is_dir():
    ROOT = ROOT/'site'

# The page reads only these parts; the full snapshots stay in research/ for review and tests.
KEEP = {'DEMAND_RESEARCH': ('schema_version', 'reviewed_at', 'report_url', 'global_estimate', 'token_estimates', 'unavailable_tokens', 'supplemental_tokens', 'future_accelerators', 'watch'),
        'RESEARCH_CAPACITY': ('schema_version', 'retrieved_utc', 'method', 'api_contract_url', 'unavailable', 'points')}

def slim(name, data):
    if name not in KEEP:
        return data
    data = {k: v for k, v in data.items() if k in KEEP[name]}
    if name == 'RESEARCH_CAPACITY':
        data['points'] = [{k: v for k, v in p.items() if k != 'raw_row'} for p in data['points']]
    return data

def build(root):
    payloads = [('DEMAND_RESEARCH', 'demand-research.json'), ('RESEARCH_CAPACITY', 'capacity-expanded.json'), ('DC_TIMELINES', 'dc-timelines.json')]
    output = ['// Generated by automation/build_research.py from research snapshots.\n']
    for global_name, filename in payloads:
        data = json.loads((root/'research'/filename).read_text())
        if data.get('schema_version') != 1:
            raise ValueError('Unsupported research schema: '+filename)
        data = slim(global_name, data)
        text = json.dumps(data, ensure_ascii=False, separators=(',', ':')).replace('</', '<\\/').replace('\u2028', '\\u2028').replace('\u2029', '\\u2029')
        output.append('window.'+global_name+' = '+text+';\n')
    (root/'data/research.js').write_text(''.join(output))

if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--root', type=Path, default=ROOT)
    args = parser.parse_args()
    build(args.root)
    print('Generated data/research.js')
