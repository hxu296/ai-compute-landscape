#!/usr/bin/env python3
"""Generate browser data from the independent review snapshots; never rewrite nc.js."""
import argparse
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]

def build(root):
    payloads = [('DEMAND_RESEARCH', 'demand-research.json'), ('RESEARCH_CAPACITY', 'capacity-expanded.json')]
    output = ['// Generated by automation/build_research.py from research snapshots.\n']
    for global_name, filename in payloads:
        data = json.loads((root/'research'/filename).read_text())
        if data.get('schema_version') != 1:
            raise ValueError('Unsupported research schema: '+filename)
        text = json.dumps(data, ensure_ascii=False, separators=(',', ':')).replace('</', '<\\/').replace('\u2028', '\\u2028').replace('\u2029', '\\u2029')
        output.append('window.'+global_name+' = '+text+';\n')
    (root/'data/research.js').write_text(''.join(output))

if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--root', type=Path, default=ROOT)
    args = parser.parse_args()
    build(args.root)
    print('Generated data/research.js')
